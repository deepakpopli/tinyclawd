#!/usr/bin/env python3
"""Bakes the fonts and symbol glyphs into components/pet/src/fonts.cpp.

small text uses the X11 misc-fixed bitmap fonts (public domain), the big words
and symbols are DejaVu rendered at the same sizes as animations/eyes.py so the
firmware looks like the gifs.

  python3 tools/gen_fonts.py
"""
import gzip
import io
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, PcfFontFile

OUT = Path(__file__).resolve().parent.parent / "components/pet/src/fonts.cpp"
MISC = "/usr/share/fonts/X11/misc/{}.pcf.gz"
DEJAVU = "/usr/share/fonts/truetype/dejavu/DejaVuSans{}.ttf"

ASCII = "".join(chr(c) for c in range(32, 127))
BIG = " !+-'0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZ"

# name, source, size, charset
FONTS = [
    ("font_4x6", "misc:4x6", 0, ASCII),
    ("font_5x7", "misc:5x7", 0, ASCII),
    ("font_6x10", "misc:6x10", 0, ASCII),
    ("font_bold12", "dejavu:-Bold", 12, BIG),
    ("font_bold16", "dejavu:-Bold", 16, BIG),
    ("font_bold24", "dejavu:-Bold", 24, BIG),
    ("font_sym14", "dejavu:", 14, "·✢✳✶✻✽✦"),
    ("font_sym12", "dejavu:", 12, "♪♫"),
    ("font_z", "dejavu:-Bold", 14, "z"),
]


def misc_glyphs(name, charset):
    data = gzip.open(MISC.format(name)).read()
    pcf = PcfFontFile.PcfFontFile(io.BytesIO(data))
    raw = [(ch, pcf.glyph[ord(ch)]) for ch in charset]
    asc = max(-g[1][1] for _, g in raw)
    desc = max(g[1][3] for _, g in raw)
    out = []
    for ch, g in raw:
        adv = g[0][0]
        cell = Image.new("1", (adv, asc + desc), 0)
        if g[3] is not None:
            cell.paste(g[3].convert("1"), (g[1][0], g[1][1] + asc))
        out.append((ch, cell, adv))
    return out, asc + desc


def ttf_glyphs(style, size, charset):
    font = ImageFont.truetype(DEJAVU.format(style), size)
    asc, desc = font.getmetrics()
    out = []
    for ch in charset:
        img = Image.new("1", (size * 2, asc + desc), 0)
        ImageDraw.Draw(img).text((0, 0), ch, fill=1, font=font)
        bbox = img.getbbox()
        adv = round(font.getlength(ch))
        if bbox is None:
            out.append((ch, Image.new("1", (1, asc + desc), 0), adv))
            continue
        out.append((ch, img.crop((0, 0, max(bbox[2], 1), asc + desc)), max(adv, bbox[2])))
    return out, asc + desc


def crop_rows(glyphs, h):
    """Drop empty rows that every glyph shares (keeps the line box tight)."""
    top, bot = h, 0
    for _, img, _ in glyphs:
        b = img.getbbox()
        if b:
            top, bot = min(top, b[1]), max(bot, b[3])
    if top >= bot:
        return glyphs, h, 0
    return [(c, i.crop((0, top, i.size[0], bot)), a) for c, i, a in glyphs], bot - top, top


def pack(img, w, h):
    px = img.load()
    rows = []
    for y in range(h):
        byte, bits, row = 0, 0, []
        for x in range(w):
            on = x < img.size[0] and y < img.size[1] and px[x, y]
            byte = (byte << 1) | (1 if on else 0)
            bits += 1
            if bits == 8:
                row.append(byte)
                byte, bits = 0, 0
        if bits:
            row.append(byte << (8 - bits))
        rows += row
    return rows


def main():
    lines = ["// generated by tools/gen_fonts.py, do not edit", "#include \"fonts.h\"", ""]
    for name, src, size, charset in FONTS:
        kind, arg = src.split(":")
        if kind == "misc":
            glyphs, h = misc_glyphs(arg, charset)
        else:
            glyphs, h = ttf_glyphs(arg, size, charset)
            if name != "font_z":
                glyphs, h, _ = crop_rows(glyphs, h)
        data, table = [], []
        for ch, img, adv in glyphs:
            w = img.size[0]
            table.append(f"    {{0x{ord(ch):04x}, {len(data)}, {w}, {adv}}},")
            data += pack(img, w, h)
        lines.append(f"static const uint8_t {name}_data[] = {{")
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append(f"static const Glyph {name}_glyphs[] = {{")
        lines += table
        lines.append("};")
        lines.append(f"const Font {name} = {{{h}, {len(glyphs)}, {name}_glyphs, {name}_data}};")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
